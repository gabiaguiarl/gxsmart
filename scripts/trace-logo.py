"""Traces the purple GX symbol from the official logo (public/assets/logo.png)
into vector contours used by the 3D mark (src/scene.js) and the SVG fallback.

Only the purple pixels (the symbol) are traced; the white "SMART" lettering is
ignored. The raster is upscaled and lightly blurred before thresholding so the
contour follows the anti-aliased edge instead of the pixel staircase; geometry is
not redrawn. Re-run after a logo change:  python3 scripts/trace-logo.py
Requires: pillow, numpy, opencv-python.
"""
import json, pathlib
import numpy as np, cv2
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
im = np.asarray(Image.open(ROOT / 'public/assets/logo.png').convert('RGBA')).astype(np.float32)
r, g, b, a = [im[..., i] for i in range(4)]
# Purple coverage: alpha weighted by "not white" (official purple #7809AC has very low green).
purple = (a / 255.0) * np.clip((150 - g) / 120.0, 0, 1)
S = 6
big = cv2.resize(purple, None, fx=S, fy=S, interpolation=cv2.INTER_CUBIC)
big = cv2.GaussianBlur(big, (0, 0), S * 0.45)
mask = (big > 0.5).astype(np.uint8)
contours, hier = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
hier = hier[0]
H = mask.shape[0]
shapes = []
for i, c in enumerate(contours):
    if hier[i][3] != -1 or cv2.contourArea(c) < (S * S * 40):
        continue  # holes are attached below; drop specks
    def simp(cc):
        return cv2.approxPolyDP(cc, S * 0.12, True)[:, 0, :].tolist()
    holes = []
    j = hier[i][2]
    while j != -1:
        if cv2.contourArea(contours[j]) > S * S * 10:
            holes.append(simp(contours[j]))
        j = hier[j][0]
    shapes.append({'outer': simp(c), 'holes': holes})

# Normalise: centre on the symbol's bounding box, height = 1, y up.
pts = np.array([p for s in shapes for p in s['outer']], dtype=np.float64)
x0, y0 = pts.min(0); x1, y1 = pts.max(0)
cx, cy, h = (x0 + x1) / 2, (y0 + y1) / 2, (y1 - y0)
norm = lambda poly: [[round((x - cx) / h, 4), round(-(y - cy) / h, 4)] for x, y in poly]
out = [{'outer': norm(s['outer']), 'holes': [norm(hh) for hh in s['holes']]} for s in shapes]
aspect = round((x1 - x0) / h, 4)
n = sum(len(s['outer']) + sum(len(hh) for hh in s['holes']) for s in out)
js = ("// GENERATED by scripts/trace-logo.py from public/assets/logo.png (official GX symbol).\n"
      "// Do not edit by hand. Units: symbol height = 1, centred, y up.\n"
      f"export const GX_ASPECT = {aspect};\n"
      f"export const GX_SHAPES = {json.dumps(out, separators=(',', ':'))};\n")
(ROOT / 'src/brand/gx-mark.js').write_text(js)
print(f'shapes={len(out)} holes={sum(len(s["holes"]) for s in out)} points={n} aspect={aspect} bytes={len(js)}')
